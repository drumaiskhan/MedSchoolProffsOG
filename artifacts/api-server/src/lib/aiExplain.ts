/* -------------------------------------------------------------------------- */
/* Provider Configuration                                                     */
/* -------------------------------------------------------------------------- */

async function getProviderConfig(): Promise<ProviderConfig> {
  const configuredProvider =
    (await getSetting("ai_provider")) ||
    process.env.AI_PROVIDER ||
    "";

  const provider = configuredProvider.trim().toLowerCase();

  let apiKey = "";
  let model = "";
  let baseUrl = "";

  if (provider === "anthropic") {
    apiKey =
      (await getSetting("ai_anthropic_key")) ||
      process.env.ANTHROPIC_API_KEY ||
      "";

    model =
      (await getSetting("ai_anthropic_model")) ||
      process.env.ANTHROPIC_MODEL ||
      "claude-sonnet-4-6";
  } else if (provider === "openai") {
    apiKey =
      (await getSetting("ai_openai_key")) ||
      process.env.OPENAI_API_KEY ||
      "";

    model =
      (await getSetting("ai_openai_model")) ||
      process.env.OPENAI_MODEL ||
      "gpt-5.6-luna";
  } else if (provider === "gemini") {
    apiKey =
      (await getSetting("ai_gemini_key")) ||
      process.env.GEMINI_API_KEY ||
      "";

    model =
      (await getSetting("ai_gemini_model")) ||
      process.env.GEMINI_MODEL ||
      "gemini-3.7-flash";
  } else if (provider === "custom") {
    apiKey =
      (await getSetting("ai_custom_key")) ||
      process.env.CUSTOM_AI_KEY ||
      "";

    model =
      (await getSetting("ai_custom_model")) ||
      process.env.CUSTOM_AI_MODEL ||
      "";

    baseUrl =
      (await getSetting("ai_custom_url")) ||
      process.env.CUSTOM_AI_URL ||
      "";
  }

  /*
   * If the selected provider has no key, try environment fallbacks.
   */
  if (!apiKey) {
    if (process.env.GEMINI_API_KEY) {
      return {
        provider: "gemini",
        apiKey: process.env.GEMINI_API_KEY,
        model:
          process.env.GEMINI_MODEL || "gemini-3.7-flash",
      };
    }

    if (process.env.OPENAI_API_KEY) {
      return {
        provider: "openai",
        apiKey: process.env.OPENAI_API_KEY,
        model:
          process.env.OPENAI_MODEL || "gpt-5.6-luna",
      };
    }

    if (process.env.ANTHROPIC_API_KEY) {
      return {
        provider: "anthropic",
        apiKey: process.env.ANTHROPIC_API_KEY,
        model:
          process.env.ANTHROPIC_MODEL || "claude-sonnet-4-6",
      };
    }

    throw new AiNotConfiguredError();
  }

  return {
    provider,
    apiKey,
    model,
    baseUrl,
  };
}

/* -------------------------------------------------------------------------- */
/* Provider Dispatcher                                                        */
/* -------------------------------------------------------------------------- */

async function generateText(
  config: ProviderConfig,
  prompt: string,
  maxTokens = 5000,
): Promise<string> {
  const {
    provider,
    apiKey,
    model,
    baseUrl,
  } = config;

  if (provider === "anthropic") {
    return generateWithAnthropic(
      apiKey,
      model,
      prompt,
      maxTokens,
    );
  }

  if (provider === "openai") {
    return generateWithOpenAi(
      apiKey,
      model,
      prompt,
      maxTokens,
    );
  }

  if (provider === "gemini") {
    return generateWithGemini(
      apiKey,
      model,
      prompt,
      maxTokens,
    );
  }

  if (provider === "custom") {
    if (!baseUrl) {
      throw new Error(
        "Custom AI provider is selected but CUSTOM_AI_URL is missing.",
      );
    }

    if (!model) {
      throw new Error(
        "Custom AI provider is selected but CUSTOM_AI_MODEL is missing.",
      );
    }

    return generateWithCustomEndpoint(
      baseUrl,
      apiKey,
      model,
      prompt,
      maxTokens,
    );
  }

  throw new Error(
    `Unsupported AI provider: ${provider || "(empty)"}`,
  );
}

