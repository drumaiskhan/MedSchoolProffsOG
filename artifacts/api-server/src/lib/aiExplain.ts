/* -------------------------------------------------------------------------- */
/* Public: Flashcard Set Generation                                          */
/* -------------------------------------------------------------------------- */

export async function generateFlashcardSet(
  request: FlashcardGenerationRequest,
): Promise<GeneratedFlashcard[]> {
  const count = Number(request.count);

  if (!Number.isFinite(count) || !Number.isInteger(count)) {
    throw new Error(
      "Flashcard count must be a whole number.",
    );
  }

  if (count < 1) {
    throw new Error(
      "Flashcard count must be at least 1.",
    );
  }

  if (count > MAX_FLASHCARDS) {
    throw new Error(
      `You can generate up to ${MAX_FLASHCARDS} flashcards at once.`,
    );
  }

  const hasSource =
    Boolean(request.sourceText?.trim()) ||
    Boolean(request.mcqs && request.mcqs.length > 0);

  if (!hasSource) {
    throw new Error(
      "Flashcard generation requires source material or MCQs.",
    );
  }

  const config = await getProviderConfig();

  const allCards: GeneratedFlashcard[] = [];

  /*
   * Generate in batches.
   *
   * Example:
   *
   * count = 50
   *
   * Batch 1 -> 20
   * Batch 2 -> 20
   * Batch 3 -> 10
   *
   * This avoids asking the AI to produce an enormous JSON response.
   */
  let remaining = count;

  let attempt = 0;

  while (
    allCards.length < count &&
    remaining > 0 &&
    attempt < MAX_GENERATION_ATTEMPTS + Math.ceil(count / FLASHCARD_BATCH_SIZE)
  ) {
    attempt++;

    const batchCount = Math.min(
      FLASHCARD_BATCH_SIZE,
      remaining,
    );

    const batchRequest: FlashcardGenerationRequest = {
      ...request,
      count: batchCount,
    };

    /*
     * Tell subsequent batches which questions have already been created.
     * This dramatically reduces duplicate cards.
     */
    const previousQuestions = allCards
      .map((card) => card.front)
      .join("\n");

    const batchPrompt = buildFlashcardGenerationPrompt(
      batchRequest,
    );

    const antiDuplicateInstruction =
      previousQuestions.length > 0
        ? [
            "",
            "IMPORTANT:",
            "The following flashcard questions have already been generated.",
            "Do NOT repeat or closely rephrase any of them.",
            "",
            previousQuestions,
          ].join("\n")
        : "";

    let rawResponse: string;

    try {
      rawResponse = await generateText(
        config,
        batchPrompt + antiDuplicateInstruction,
        6000,
      );
    } catch (error) {
      /*
       * If this was a temporary provider failure and we already have
       * some cards, stop cleanly with the cards we successfully generated.
       */
      if (allCards.length > 0) {
        break;
      }

      throw error;
    }

    let batchCards: GeneratedFlashcard[];

    try {
      batchCards = parseFlashcardJson(rawResponse);
    } catch (error) {
      /*
       * Retry the same batch once with a stronger JSON instruction.
       */
      const retryPrompt = [
        batchPrompt,

        "",
        "CRITICAL JSON REQUIREMENT:",
        `Return exactly ${batchCount} objects.`,
        "Return ONLY the JSON array.",
        "No markdown.",
        "No code fences.",
        "No explanation.",
        "Every object must contain both a non-empty front and back field.",
      ].join("\n");

      try {
        const retryResponse = await generateText(
          config,
          retryPrompt,
          6000,
        );

        batchCards = parseFlashcardJson(retryResponse);
      } catch {
        if (allCards.length > 0) {
          break;
        }

        throw error;
      }
    }

    const before = allCards.length;

    addUniqueCards(
      allCards,
      batchCards,
      count,
    );

    const added = allCards.length - before;

    /*
     * If the AI returned nothing new, ask again rather than looping forever.
     */
    if (added === 0) {
      if (allCards.length >= count) {
        break;
      }

      if (attempt >= MAX_GENERATION_ATTEMPTS) {
        break;
      }

      continue;
    }

    remaining = count - allCards.length;
  }

  /*
   * Return exactly the requested number when enough unique cards were
   * generated.
   */
  return allCards.slice(0, count);
}
